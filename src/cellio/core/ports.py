from collections.abc import Mapping
from typing import Protocol

from .models import (
    ActuationReceipt,
    AdvanceReceipt,
    ControllerOutput,
    ControllerView,
    DeliveryDecision,
    RequirementResult,
    SignalSample,
    Tick,
    TickEvidenceFrame,
    TruthSnapshot,
)


class PlantPort(Protocol):
    def load(self, scene_config: Mapping) -> None: ...
    def reset(self, initial_state: Mapping, generation: int) -> None: ...
    def snapshot(self, tick: Tick) -> TruthSnapshot: ...
    def apply(
        self, commands: tuple[DeliveryDecision, ...], overrides: Mapping, tick: Tick
    ) -> ActuationReceipt: ...
    def advance_one_step(self, render: bool = False) -> AdvanceReceipt: ...
    def close(self) -> None: ...


class SignalMapperPort(Protocol):
    def reset(self, generation: int) -> None: ...
    def sample(
        self, truth: TruthSnapshot, tick: Tick
    ) -> Mapping[str, SignalSample]: ...


class ControllerPort(Protocol):
    def reset(self, config: Mapping, initial_view: ControllerView) -> None: ...
    def tick(self, view: ControllerView, tick: Tick) -> ControllerOutput: ...
    def close(self) -> None: ...


class OraclePort(Protocol):
    def reset(self, requirements: tuple[Mapping, ...], generation: int) -> None: ...
    def observe(self, frame: TickEvidenceFrame) -> tuple[RequirementResult, ...]: ...
    def finalize(
        self, final_tick: Tick, complete_horizon: bool
    ) -> tuple[RequirementResult, ...]: ...


class TracePort(Protocol):
    def start(self, manifest: Mapping) -> None: ...
    def append_tick(
        self, frame: TickEvidenceFrame, verdicts: tuple[RequirementResult, ...]
    ) -> None: ...
    def finish(self, result_summary: Mapping, artifact_complete: bool) -> Mapping: ...
